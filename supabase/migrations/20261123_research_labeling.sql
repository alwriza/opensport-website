-- ============================================================
-- Research labeling tool (match analysis, research phase)
--
-- Admin-only pages under /admin/research. The CEO adds YouTube matches, labels a
-- blind gold set, and later reviews model predictions. The GPU pipeline writes
-- predictions with the service-role key (it bypasses RLS).
--
-- Rules
--  * Every table: RLS on, clients allowed only when is_admin() is true
--    (is_admin() comes from 20261108_creator_referrals.sql).
--  * A match is added only through research_add_match(): it validates the input,
--    gives the match its id (match001, match002, ...) and creates its 10-minute
--    segment. The first match of each camera type becomes a gold segment, every
--    later one a review segment.
--  * Gold stays blind in the database: clients can never read predictions of a
--    gold segment, and labels can only be written on gold segments.
--  * Every time (t, start_s, end_s, kickoff_s, position_s) is in seconds from the
--    start of the YouTube video; the pipeline writes predictions on the same clock.
--
-- Admins: add a row to public.admin_users by hand, e.g.
--   INSERT INTO public.admin_users (auth_user_id, note)
--   SELECT id, 'research' FROM auth.users WHERE email = 'ceo@example.com';
-- ============================================================


-- ==================== TABLES ====================

CREATE SEQUENCE IF NOT EXISTS public.research_match_seq;

CREATE TABLE IF NOT EXISTS public.research_matches (
  id            text PRIMARY KEY DEFAULT ('match' || lpad(nextval('public.research_match_seq')::text, 3, '0')),
  youtube_id    text NOT NULL UNIQUE CHECK (youtube_id ~ '^[A-Za-z0-9_-]{11}$'),
  url           text NOT NULL,
  title         text,
  duration_s    numeric NOT NULL CHECK (duration_s > 0),
  league        text NOT NULL CHECK (length(btrim(league)) > 0),
  format        text NOT NULL CHECK (format IN ('11x11', '8x8', '7x7')),
  camera_type   text NOT NULL CHECK (camera_type IN ('static', 'operator', 'phone')),
  quality       text NOT NULL CHECK (quality IN ('720p', '1080p', '4k')),
  surface       text NOT NULL CHECK (surface IN ('artificial', 'natural')),
  lighting      text NOT NULL CHECK (lighting IN ('day', 'floodlights')),
  team_a_color  text NOT NULL CHECK (length(btrim(team_a_color)) > 0),
  team_b_color  text NOT NULL CHECK (length(btrim(team_b_color)) > 0),
  kickoff_s     numeric NOT NULL CHECK (kickoff_s >= 0),
  notes         text,
  -- new -> downloaded (download.sh) -> processed (run_batch.py); error with a reason.
  status        text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'downloaded', 'processed', 'error')),
  error         text,
  created_by    uuid DEFAULT auth.uid(),
  created_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (kickoff_s + 720 <= duration_s)
);

CREATE TABLE IF NOT EXISTS public.research_segments (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  match_id        text NOT NULL UNIQUE REFERENCES public.research_matches(id) ON DELETE CASCADE,
  start_s         numeric NOT NULL CHECK (start_s >= 0),
  end_s           numeric NOT NULL,
  mode            text NOT NULL CHECK (mode IN ('gold', 'review')),
  -- gold starts 'ready' (needs no model); review waits for the pipeline's predictions.
  status          text NOT NULL CHECK (status IN ('waiting', 'ready', 'in_progress', 'done')),
  position_s      numeric,
  -- Review only: which model cluster (0/1) is team A. Set by one click before reviewing.
  team_a_cluster  smallint CHECK (team_a_cluster IN (0, 1)),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CHECK (end_s > start_s)
);

CREATE TABLE IF NOT EXISTS public.research_labels (
  id            uuid PRIMARY KEY,  -- generated by the client, so a resent write is not a duplicate
  segment_id    uuid NOT NULL REFERENCES public.research_segments(id) ON DELETE CASCADE,
  t             numeric NOT NULL CHECK (t >= 0),
  class         text NOT NULL CHECK (class IN ('pass', 'drive', 'cross', 'shot', 'header', 'tackle', 'block', 'throw_in')),
  team          text NOT NULL CHECK (team IN ('A', 'B')),
  shot_outcome  text CHECK (shot_outcome IN ('goal', 'on_target', 'off_target', 'blocked')),
  unsure        boolean NOT NULL DEFAULT false,
  created_by    uuid DEFAULT auth.uid(),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CHECK ((class = 'shot') = (shot_outcome IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.research_predictions (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  segment_id  uuid NOT NULL REFERENCES public.research_segments(id) ON DELETE CASCADE,
  source      text NOT NULL CHECK (source IN ('tdeed', 'rules')),
  t           numeric NOT NULL CHECK (t >= 0),
  raw_class   text NOT NULL,
  -- NULL for model classes that are not reviewed (GOAL, OUT).
  class       text CHECK (class IN ('pass', 'drive', 'cross', 'shot', 'header', 'tackle', 'block', 'throw_in')),
  confidence  real NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
  -- Model team cluster of the player nearest the ball; NULL when no ball was found.
  cluster     smallint CHECK (cluster IN (0, 1)),
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.research_reviews (
  prediction_id  uuid PRIMARY KEY REFERENCES public.research_predictions(id) ON DELETE CASCADE,
  verdict        text NOT NULL CHECK (verdict IN ('correct', 'not_event', 'relabel')),
  class          text CHECK (class IN ('pass', 'drive', 'cross', 'shot', 'header', 'tackle', 'block', 'throw_in')),
  team           text CHECK (team IN ('A', 'B')),
  t              numeric,
  shot_outcome   text CHECK (shot_outcome IN ('goal', 'on_target', 'off_target', 'blocked')),
  unsure         boolean NOT NULL DEFAULT false,
  reviewed_by    uuid DEFAULT auth.uid(),
  reviewed_at    timestamptz NOT NULL DEFAULT now(),
  CHECK ((verdict = 'not_event') = (class IS NULL)),
  CHECK (verdict = 'not_event' OR team IS NOT NULL),
  CHECK (verdict = 'not_event' OR ((class = 'shot') = (shot_outcome IS NOT NULL)))
);

CREATE INDEX IF NOT EXISTS research_labels_segment_idx      ON public.research_labels (segment_id, t);
CREATE INDEX IF NOT EXISTS research_predictions_segment_idx ON public.research_predictions (segment_id, t);


-- ==================== ROW LEVEL SECURITY ====================

ALTER TABLE public.research_matches     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_segments    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_labels      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_predictions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_reviews     ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.research_matches, public.research_segments, public.research_labels,
              public.research_predictions, public.research_reviews
  FROM anon, authenticated;

GRANT SELECT                          ON public.research_matches     TO authenticated;
GRANT SELECT                          ON public.research_segments    TO authenticated;
-- Clients change only progress, status and the team-A click; mode, bounds and match stay as created.
GRANT UPDATE (status, position_s, team_a_cluster, updated_at) ON public.research_segments TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE  ON public.research_labels      TO authenticated;
GRANT SELECT                          ON public.research_predictions TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE  ON public.research_reviews     TO authenticated;

DROP POLICY IF EXISTS "Admins read research matches" ON public.research_matches;
CREATE POLICY "Admins read research matches" ON public.research_matches
  FOR SELECT TO authenticated USING (public.is_admin());

DROP POLICY IF EXISTS "Admins read research segments" ON public.research_segments;
CREATE POLICY "Admins read research segments" ON public.research_segments
  FOR SELECT TO authenticated USING (public.is_admin());

DROP POLICY IF EXISTS "Admins update research segments" ON public.research_segments;
CREATE POLICY "Admins update research segments" ON public.research_segments
  FOR UPDATE TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

-- Labels exist only on gold segments.
DROP POLICY IF EXISTS "Admins manage gold labels" ON public.research_labels;
CREATE POLICY "Admins manage gold labels" ON public.research_labels
  FOR ALL TO authenticated
  USING (public.is_admin() AND EXISTS (
    SELECT 1 FROM public.research_segments s WHERE s.id = segment_id AND s.mode = 'gold'))
  WITH CHECK (public.is_admin() AND EXISTS (
    SELECT 1 FROM public.research_segments s WHERE s.id = segment_id AND s.mode = 'gold'));

-- Gold stays blind: predictions of gold segments are never readable from a client.
DROP POLICY IF EXISTS "Admins read review predictions" ON public.research_predictions;
CREATE POLICY "Admins read review predictions" ON public.research_predictions
  FOR SELECT TO authenticated
  USING (public.is_admin() AND EXISTS (
    SELECT 1 FROM public.research_segments s WHERE s.id = segment_id AND s.mode = 'review'));

DROP POLICY IF EXISTS "Admins manage reviews" ON public.research_reviews;
CREATE POLICY "Admins manage reviews" ON public.research_reviews
  FOR ALL TO authenticated
  USING (public.is_admin() AND EXISTS (
    SELECT 1 FROM public.research_predictions p
    JOIN public.research_segments s ON s.id = p.segment_id
    WHERE p.id = prediction_id AND s.mode = 'review'))
  WITH CHECK (public.is_admin() AND EXISTS (
    SELECT 1 FROM public.research_predictions p
    JOIN public.research_segments s ON s.id = p.segment_id
    WHERE p.id = prediction_id AND s.mode = 'review'));


-- ==================== ADD A MATCH ====================

CREATE OR REPLACE FUNCTION public.research_add_match(
  p_youtube_id   text,
  p_url          text,
  p_duration_s   numeric,
  p_league       text,
  p_format       text,
  p_camera_type  text,
  p_quality      text,
  p_surface      text,
  p_lighting     text,
  p_team_a_color text,
  p_team_b_color text,
  p_kickoff_s    numeric,
  p_notes        text
)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_id   text;
  v_mode text;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'not_authorized' USING ERRCODE = '42501';
  END IF;
  IF EXISTS (SELECT 1 FROM public.research_matches WHERE youtube_id = p_youtube_id) THEN
    RAISE EXCEPTION 'duplicate_video';
  END IF;
  IF p_kickoff_s + 720 > p_duration_s THEN
    RAISE EXCEPTION 'too_short';
  END IF;

  -- One gold segment per camera type: serialize the check against parallel adds.
  PERFORM pg_advisory_xact_lock(hashtext('research_add_match'));

  INSERT INTO public.research_matches (
    youtube_id, url, duration_s, league, format, camera_type, quality, surface,
    lighting, team_a_color, team_b_color, kickoff_s, notes)
  VALUES (
    p_youtube_id, p_url, p_duration_s, btrim(p_league), p_format, p_camera_type, p_quality,
    p_surface, p_lighting, btrim(p_team_a_color), btrim(p_team_b_color), p_kickoff_s,
    NULLIF(btrim(coalesce(p_notes, '')), ''))
  RETURNING id INTO v_id;

  v_mode := CASE WHEN EXISTS (
      SELECT 1 FROM public.research_segments s
      JOIN public.research_matches m ON m.id = s.match_id
      WHERE s.mode = 'gold' AND m.camera_type = p_camera_type)
    THEN 'review' ELSE 'gold' END;

  INSERT INTO public.research_segments (match_id, start_s, end_s, mode, status)
  VALUES (v_id, p_kickoff_s + 120, p_kickoff_s + 720, v_mode,
          CASE WHEN v_mode = 'gold' THEN 'ready' ELSE 'waiting' END);

  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.research_add_match(text, text, numeric, text, text, text, text, text, text, text, text, numeric, text) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.research_add_match(text, text, numeric, text, text, text, text, text, text, text, text, numeric, text) TO authenticated;
